# --------------------------------------------------------------------------
# 评量编码
# --------------------------------------------------------------------------


class EvalCode(str, Enum):
    """评量编码。**经带教老师确认**：P = 达标，E = 未达标。"""

    PASS = "P"      # 达标
    FAIL = "E"      # 未达标

    @property
    def is_pass(self) -> bool:
        return self is EvalCode.PASS


CODE_CHARS = "PE"

# 单元格里出现这些词表示该次评量未参加，属于真正的缺失
ABSENT_TOKENS = ("未参与", "未参加", "缺席", "请假", "未评")

# 语料里出现 21 次字母 `F`（如 `EFEE` / `EEF` / `PEF`），
# 规律：只落在第 2、3 位、总与 E 相邻、同一批幼儿跨多份教案重复相同模式，
# 判定为键盘 E/F 相邻导致的笔误，按 E 处理。
LETTER_FIXES = {"F": "E"}


def parse_code(raw: str) -> List[EvalCode]:
    """把 'P   PP' / 'E  E E' / 'EFEE' 解析为编码列表。

    - `F` 按笔误修正为 `E`（见 LETTER_FIXES 说明）
    - 传入 '未参与' 这类缺失标记时返回空列表，表示该次无数据
    """
    text = (raw or "").strip()
    if not text or any(tok in text for tok in ABSENT_TOKENS):
        return []
    text = re.sub(r"\s+", "", text).upper()
    for bad, good in LETTER_FIXES.items():
        text = text.replace(bad, good)
    cleaned = re.sub(r"[^PE]", "", text)
    return [EvalCode(ch) for ch in cleaned]


# --------------------------------------------------------------------------
# 达标率 -> 支持层级映射
# --------------------------------------------------------------------------

# 阈值取自「康教班级可接受的支持强度」经验区间，可随带教老师意见调整
MASTERY_TO_SUPPORT: List[Tuple[float, str]] = [
    (0.80, "独立完成"),
    (0.60, "手势辅助"),
    (0.40, "少量身体辅助"),
    (0.20, "大量身体辅助"),
    (0.00, "示范模仿"),
]


def support_from_mastery(mastery: float, absent: bool = False) -> str:
    if absent:
        return "未参与"
    for threshold, level in MASTERY_TO_SUPPORT:
        if mastery >= threshold:
            return level
    return "示范模仿"


