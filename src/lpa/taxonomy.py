# 认知理解统一归并到「认知」
DOMAIN_ALIAS = {"认知理解": "认知"}


BEHAVIOR_CLAUSE = re.compile(r"[^。；\d]{0,24}(?:安坐|闹情绪|走出位置)[^。；]{0,14}")


def classify_domain(text: str) -> str:
    """把一条康复目标文本归到发展领域。

    模板里「整节课堂能安坐好不走出位置不闹情绪」是每份教案的固定开场白，
    它会污染领域判定，因此先把这类从句摘掉再分类。
    """
    probe = text
    if is_classroom_behavior_goal(text) and len(text) > 24:
        probe = BEHAVIOR_CLAUSE.sub("", text).strip()
        if len(probe) < 6:
            probe = text
    for domain, keywords in DOMAIN_KEYWORDS:
        if any(k in probe for k in keywords):
            return DOMAIN_ALIAS.get(domain, domain)
    return "未分类"


BOILERPLATE_MARKERS = ("安坐", "坐好", "不闹情绪", "不走出位置", "走出位置")


def is_classroom_behavior_goal(text: str) -> bool:
    """判断是否为每份教案开头固定的「课堂安坐」类目标（模板化条目）。"""
    return any(m in text for m in BOILERPLATE_MARKERS)


def ladder_of(text: str) -> List[str]:
    """从一条目标文本里抽出「辅助梯级」，用于还原教师的支架递进写法。"""
    hits = [lv for lv, kws in SUPPORT_KEYWORDS if any(k in text for k in kws)]
    return hits


# --------------------------------------------------------------------------
# 主题归一：剥掉主题自带的引导动词
# --------------------------------------------------------------------------

# 语料里的主题常以「动词 + 宾语」形式出现（「认识秋天的水果」「我会穿鞋子」
# 「跟着音乐做动作」）。直接把它当宾语嵌进目标句，就会生成
# 「能认识认识秋天的水果的相关内容」这类病句。这里把引导动词剥掉，
# 只留**真实内容词**（「秋天的水果」），供生成层当宾语用。
_THEME_VERB_PREFIXES: Tuple[str, ...] = (
    "跟着", "学做", "学习", "练习", "认识", "了解", "会做", "我会", "会",
    "一起", "尝试", "复习", "巩固", "感受", "体验", "做一做", "做",
)


def strip_theme_verb(theme: str) -> str:
    """剥掉主题的引导动词，返回可作宾语的核心内容词。

    「认识秋天的水果」→「秋天的水果」
    「我会穿鞋子」    →「穿鞋子」
    「跟着音乐做动作」→「音乐做动作」   ← 长前缀优先，避免只剥出「音乐做动作」
    「玩球」          →「球」
    「秋天的水果」    →「秋天的水果」（无前缀，原样返回）

    注意：剥剩不足 2 字时原样返回，避免把主题剥空。
    """
    t = (theme or "").strip()
    if not t:
        return t
    # 长前缀优先，保证「跟着」先于「会」之类被匹配
    for p in sorted(_THEME_VERB_PREFIXES, key=len, reverse=True):
        if t.startswith(p) and len(t) - len(p) >= 2:
            return t[len(p):]
    return t


